"""直前の操作の続きを、言い直さずに指示できるようにする。

判定（Jev）に渡す前の段階で、決まった言い方だけをここで拾う。文脈（何を開いたか・どこまで実行したか）は
controller が持ち、この module は「どの種類の続きか」だけを判定する。

  「続き」「残りをやって」      → resume  途中で止まった／失敗した手順の続きから実行
  「さっきのページ」「その動画」 → page    直前に開いた URL をもう一度開く（無ければ直前のサイト・検索語）
  「さっきのアプリ」            → app     直前に起動・切り替えたアプリを前面に出す
  「さっきのやつ」「もう一回」   → again   直前の命令をもう一度
  「それ開いて」「これ見せて」   → that    直前に扱ったもの（ページ → アプリの順に解決）
  「これ覚えて」「今のを覚えて」 → learn   直前に実行した言い方を覚える（次からは判定を通さず実行）
  「それ忘れて」                → forget  覚えた言い方を忘れる
  「何覚えてる」「覚えたこと見せて」→ knowledge 覚えている言い方と回数を表示
"""
from __future__ import annotations

import re

_POLITE = r"(ください|下さい|お願い|おねがい|ちょっと|ね|よ)*"
_RESUME = re.compile(r"^(その|さっきの|あの)?(続き|つづき|残り|のこり)(を)?"
                     r"(やって|実行して|実行|進めて|お願い|おねがい|して|見せて|再開して)?" + _POLITE + r"$")
_PAGE = re.compile(r"^(さっき|その|あの)(の)?(サイト|ページ|URL|ユーアールエル|検索結果|動画|記事|タブ)(を)?"
                   r"(もう一度|もういちど|もっかい|再度)?"
                   r"(開いて|ひらいて|開き直して|出して|だして|表示して|見せて|再生して|見て)?" + _POLITE + r"$")
_APP = re.compile(r"^(さっき|その|あの)(の)?(アプリ|ソフト|ウィンドウ|画面)(を)?"
                  r"(もう一度|もっかい|再度)?(に|へ)?"
                  r"(開いて|ひらいて|出して|だして|表示して|見せて|前に出して|戻して|もどして|戻って|もどって|復帰して|切り替えて)?" + _POLITE + r"$")
_AGAIN = re.compile(r"^(さっきの|その|あの)(やつ|もの|の)(を)?(もう一度|もういちど|もう一回|もう1回|もっかい|再度)?"
                    r"(やって|実行して|実行|お願い|おねがい|して|見せて)?" + _POLITE + r"$")
_THAT = re.compile(r"^(それ|これ)(を)?"
                   r"(もう一度|もういちど|もっかい)?"
                   r"(開いて|ひらいて|出して|だして|表示して|見せて|再生して|見て|やって)" + _POLITE + r"$")
# 学習：「これ覚えて」「今のを覚えておいて」→ 直前に実行した言い方を覚える
_LEARN = re.compile(r"^(これ|それ|今の|いまの|この言い方|このやり方)(を)?"
                    r"(覚えて|おぼえて|記憶して|登録して|学習して)(おいて|といて)?" + _POLITE + r"$")
# 学習：「これ忘れて」→ 覚えた言い方を忘れる
_FORGET = re.compile(r"^(これ|それ|今の|いまの|この言い方)?(を)?"
                     r"(忘れて|わすれて|忘れておいて|覚え直して)" + _POLITE + r"$")
# 学習：「何覚えた」「覚えたこと見せて」→ 覚えている内容を表示
_KNOWLEDGE = re.compile(r"(?:(?:何|なに|どんな)(?:を)?(?:覚えて|おぼえて)(?:いる|る|るの)?"
                        r"|(?:覚えたこと|覚えていること|学習の状況|学習したこと)(?:を)?(?:見せて|みせて|教えて|おしえて|確認|表示して|一覧)?)"
                        + _POLITE + r"$")


def kind(text: str) -> str | None:
    """続きの指示なら種類（resume / page / app / again / that / learn / forget / knowledge）を返す。違えば None。

    判定は語尾まで含めた完全一致に近い形にして、普通の命令（「そのページを検索して」など）を
    横取りしないようにする。
    """
    c = re.sub(r"[\s　]", "", text).strip().rstrip("。．.！!？?")
    if not c:
        return None
    for pattern, name in ((_RESUME, "resume"), (_PAGE, "page"), (_APP, "app"), (_AGAIN, "again"),
                          (_THAT, "that"), (_LEARN, "learn"), (_FORGET, "forget"),
                          (_KNOWLEDGE, "knowledge")):
        if pattern.fullmatch(c):
            return name
    return None
